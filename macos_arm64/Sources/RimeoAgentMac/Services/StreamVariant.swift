import Foundation

/// В каком виде файл уезжает клиенту по `/stream`.
///
/// Вынесено из `APIRouter.streamAudio` в чистую функцию намеренно: правило выбора уже
/// выстрелило дважды. Сначала — тем, что зависело от `src` («кто спросил»), из-за чего один
/// и тот же трек приезжал в iOS как AIFF через туннель и как WAV по локальной сети; клиентский
/// префиксный кеш склеил голову одного с хвостом другого, и это игралось как громкий белый шум
/// (баг-репорт #83). Здесь решение можно прогнать тестами целиком, без сокета и без файлов.
///
/// Значение уходит клиенту заголовком `X-Rimeo-Variant`, и клиентский кеш сверяет его с тем,
/// из чего собран его префикс.
enum StreamVariant: String {
    /// Байт-в-байт исходный файл.
    case original
    /// AIFF, сконвертированный в WAV (веб-плеер: wavesurfer не декодирует AIFF).
    case wav
    /// Hi-res, пересчитанный в 16-бит/44.1/стерео WAV (иначе не пролезает в туннель).
    case wav16

    /// Единственный источник правды о том, что отдавать.
    ///
    /// Приоритет намеренно такой:
    /// 1. `raw=1` / `fmt=original` — явное «нужен оригинал» (скачивание, офлайн, качество);
    /// 2. hi-res — ограничение канала, применяется ко ВСЕМ клиентам одинаково;
    /// 3. `fmt=wav` — явный запрос конверсии, не зависящий от того, кем клиент представился;
    /// 4. эвристика по `src` — только как обратная совместимость для клиентов, которые
    ///    ничего явного не просят (старый веб-плеер).
    ///
    /// - Parameters:
    ///   - ext: расширение файла в нижнем регистре, без точки.
    ///   - bitrate: битрейт из Rekordbox; 0 = неизвестен (тогда hi-res-ветка не применяется).
    static func decide(ext: String,
                       raw: Bool,
                       fmt: String,
                       src: String,
                       bitrate: Int,
                       hiResThreshold: Int) -> StreamVariant {
        if raw || fmt == "original" { return .original }
        if bitrate > hiResThreshold { return .wav16 }
        let isAIFF = (ext == "aif" || ext == "aiff")
        if isAIFF && (fmt == "wav" || src != "ios") { return .wav }
        return .original
    }
}
